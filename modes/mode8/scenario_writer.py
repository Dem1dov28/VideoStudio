def validate_stage_sequence(stage_keys: list[str]) -> list[str]:
    """
    Validate and fix stage sequence to ensure logical construction flow.
    
    This prevents impossible transitions like:
    - Roof appearing before walls
    - Windows appearing before roof
    - Facade finishing before walls exist
    
    Args:
        stage_keys: List of stage keys in proposed order
        
    Returns:
        Validated list of stage keys (may be reordered if needed)
    """
    # Define valid transitions and dependencies
    # Each stage can only be included if its dependencies are present
    dependencies = {
        "empty_land": [],
        "land_preparation": ["empty_land"],
        "foundation": ["empty_land"],  # Can come after empty_land or land_preparation
        "walls": ["foundation"],
        "roof": ["walls"],
        "windows_doors": ["walls"],  # Can come after walls (before or after roof)
        "finishing": ["walls"],  # Needs walls, ideally after windows
        "landscaping": ["walls"],  # Final stage, needs at least walls
    }
    
    # Logical order for construction (used for reordering if needed)
    logical_order = [
        "empty_land",
        "land_preparation", 
        "foundation",
        "walls",
        "roof",
        "windows_doors",
        "finishing",
        "landscaping",
    ]
    
    # Filter to only valid stages and sort by logical order
    valid_stages = [s for s in stage_keys if s in logical_order]
    ordered_stages = sorted(valid_stages, key=lambda x: logical_order.index(x))
    
    # Ensure we have minimum required stages
    if "empty_land" not in ordered_stages:
        ordered_stages.insert(0, "empty_land")
    
    if "landscaping" not in ordered_stages:
        ordered_stages.append("landscaping")
    
    # Ensure walls come before roof
    if "roof" in ordered_stages and "walls" in ordered_stages:
        roof_idx = ordered_stages.index("roof")
        walls_idx = ordered_stages.index("walls")
        if roof_idx < walls_idx:
            # Swap them - walls must come first
            ordered_stages[roof_idx], ordered_stages[walls_idx] = ordered_stages[walls_idx], ordered_stages[roof_idx]
    
    # Ensure foundation comes before walls
    if "walls" in ordered_stages and "foundation" in ordered_stages:
        walls_idx = ordered_stages.index("walls")
        foundation_idx = ordered_stages.index("foundation")
        if walls_idx < foundation_idx:
            ordered_stages[foundation_idx], ordered_stages[walls_idx] = ordered_stages[walls_idx], ordered_stages[foundation_idx]
    
    return ordered_stages


